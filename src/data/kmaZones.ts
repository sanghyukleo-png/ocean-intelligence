const BY_CODE = new Map(KMA_MARINE_ZONES.map((z) => [z[0], z]));

/** 특보 통보문 속 구역명 표기 차이("인천ㆍ경기", "인천.경기", 공백)를 흡수한 비교 키 */
export function zoneNameKey(name: string) {
  return name.replace(/[\s·ㆍ.・]/g, "");
}

const BY_NAME = new Map(KMA_MARINE_ZONES.map((z) => [zoneNameKey(z[1]), z[0]]));

export function zoneCodeByName(name: string): string | null {
  return BY_NAME.get(zoneNameKey(name)) ?? null;
}

export function zoneName(code: string): string {
  return BY_CODE.get(code)?.[1] ?? code;
}

/** 자기 자신 + 상위 구역 코드(전해상 제외). 상위 구역에 내린 특보는 하위 구역에도 적용된다. */
export function zoneWithAncestors(code: string): string[] {
  const out: string[] = [];
  let cur: string | null = code;
  while (cur && cur !== "S1000000") {
    out.push(cur);
    cur = BY_CODE.get(cur)?.[2] ?? null;
  }
  return out;
}
